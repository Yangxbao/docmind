package com.docmind.common;

import java.util.Set;

/**
 * 中英文停用词表。
 * 这些词几乎每篇文档都会出现（"的""是""the"……），对"区分文档"毫无帮助，
 * 分词之后必须先过滤掉，否则词频统计和向量化都会被它们污染。
 * 这里内置了一份精简版，够个人文档场景使用；如需更精细可替换为哈工大停用词表。
 */
public final class StopWords {

    public static final Set<String> WORDS = Set.of(
            // 中文单字
            "的", "了", "和", "是", "就", "都", "而", "及", "与", "着", "或", "在",
            "有", "人", "这", "那", "也", "很", "到", "说", "要", "去", "会", "看",
            "好", "吗", "呢", "吧", "啊", "把", "被", "从", "对", "为", "等", "中",
            "上", "下", "里", "个",
            // 中文双字及以上
            "一个", "一些", "一下", "没有", "我们", "你们", "他们", "她们", "它们",
            "自己", "这个", "那个", "这些", "那些", "什么", "怎么", "怎样", "如何",
            "可以", "可能", "需要", "应该", "通过", "进行", "如果", "因为", "所以",
            "因此", "但是", "然而", "并且", "以及", "对于", "关于", "由于", "之后",
            "然后", "还有", "就是", "等等", "如下", "以下", "上面", "下面", "使用",
            "时候", "现在", "已经", "出来", "起来", "这样", "那样", "一样",
            // 英文
            "the", "a", "an", "of", "to", "in", "and", "or", "is", "are", "was",
            "were", "for", "on", "with", "as", "by", "at", "from", "this", "that",
            "it", "be", "have", "has", "not", "but", "we", "you", "they", "he", "she"
    );

    private StopWords() {
    }

    public static boolean isStopWord(String word) {
        return WORDS.contains(word);
    }
}
